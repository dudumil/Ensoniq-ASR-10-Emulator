#!/usr/bin/env python3
"""Generates src/panel_art.h: the printed legends of the rack front panel, as 4-bit alpha
bitmaps, for the SDL front end.

Usage: python3 tools/make_panel_art.py [path/to/FreeSans.ttf]

Positions are in "panel units": the coordinates of a 1870 x 515 front panel (rack ears
included), measured on a photo of an ASR-10 rack. The front end scales them to the window.
Only the functional legends are drawn (button names, numbers, section names); logos and
the model name are left out.
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/freefont/FreeSans.ttf'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'panel_art.h')
RES = 2.25            # texels per panel unit (the window shows ~0.75 px per unit, so 3x)

# colour classes
GREY, YELLOW, BLUE, SMALL = 0, 1, 2, 3
# (text, x, y, size, colour, anchor)   x/y = centre of the text (anchor 'l': x = left edge)
L = []
def lab(t, x, y, size=12, col=GREY, anchor='c'): L.append((t, x, y, size, col, anchor))

# ---- input section, power, phones, volume
lab('Peak', 318, 230, 10); lab('Signal', 318, 258, 10)
lab('SCSI Activity', 1746.5, 199, 10)   # under the SCSI activity LED, over the floppy drive
lab('A/Left', 288, 277, 10); lab('B/Right', 350, 277, 10)
lab('Input Level', 318, 304, 15, BLUE)
lab('On', 268, 394, 13); lab('Power', 268, 506, 13); lab('Phones', 268, 592, 13)
lab('Volume', 348, 646, 15, BLUE)
# ---- parameter buttons (names above, numbers below in blue)
cols = (454.5, 517, 579.5)
for i, (a, b, c) in enumerate((('Env 1', 'Env 2', 'Env 3'), ('Pitch', 'Filters', 'Amp'), ('LFO', 'Wave', 'Layer'))):
    # rows at y 220 / 291 / 362 (25 high): names 25.5 above the button centre, numbers 25.5 below
    ty = (207, 278, 349)[i]; ny = (258, 329, 400)[i]
    for x, t in zip(cols, (a, b, c)): lab(t, x, ty, 13)
    for k, x in enumerate(cols): lab(str(i * 3 + k + 1), x, ny, 15, BLUE)
lab('Sample', 454.5, 420, 13); lab('Track', 517, 420, 13, YELLOW); lab('FX Select', 579.5, 420, 13)   # row centre 445.5
lab('Source', 454.5, 471, 13); lab('Select', 454.5, 485, 13); lab('0', 517, 471, 15, BLUE); lab('FX Bypass', 579.5, 471, 13)
lab('Selected', 517, 513, 11)
lab('Source Monitor', 517, 600, 11); lab('A', 454.5, 619, 14); lab('B', 579.5, 619, 14)   # LEDs 44 above / below the centre (556)
lab('Audio Tracks', 513, 644, 15, BLUE)
# ---- mode buttons
lab('Mode', 826.5, 395, 14, BLUE)
lab('Load', 765.5, 423, 13); lab('Command', 827.1, 423, 13); lab('Edit', 888.7, 423, 13)
lab('(Select', 765.5, 468, 10, BLUE); lab('Preset)', 765.5, 481, 10, BLUE)   # 22.5 below the centre (445.5), like the names above
lab('(Create', 827.1, 468, 10, BLUE); lab('Preset)', 827.1, 481, 10, BLUE)
lab('Instrument', 1011.9, 423, 13)
lab('Seq', 1073.5, 408, 13, YELLOW); lab('Song', 1073.5, 423, 13, YELLOW)
lab('System', 1135.1, 408, 13); lab('MIDI', 1135.1, 423, 13); lab('Effects', 1196.7, 423, 13)
lab('(Directory)', 1135.1, 468, 10, BLUE)
# ---- instruments / sequence tracks
for i in range(8): lab(str(i + 1), 765.5 + 61.6 * i, 590, 16)   # 34 below the centre (556), like Cancel / No
lab('Loaded (red)', 1240, 493, 10, GREY, 'l'); lab('Selected (yellow)', 1240, 510, 10, GREY, 'l')
lab('Instruments', 970, 623, 15, BLUE); lab('Sequence Tracks', 970, 643, 15, BLUE)
# ---- transport, arrows, cancel/enter, data entry
lab('Record', 1377.5, 207, 13); lab('Stop', 1439.5, 207, 13); lab('Play', 1501.5, 207, 13)
lab('Continue', 1439.5, 258, 13)   # 25.5 from the centre (232.5) like the names above
# (the arrow triangles are drawn by the front end)
lab('Cancel', 1377.5, 522, 13); lab('No', 1377.5, 590, 13)
lab('Enter', 1501.5, 522, 13); lab('Yes', 1501.5, 590, 13)
lab('Data Entry', 1605, 641, 15, BLUE)

fonts = {}
def font(size):
    px = round(size * RES)
    if px not in fonts: fonts[px] = ImageFont.truetype(FONT, px)
    return fonts[px]

alpha = bytearray()
entries = []
for t, x, y, size, col, anchor in L:
    f = font(size)
    l, top, r, b = f.getbbox(t)
    # vertical metrics from a reference string so labels on one row share a baseline
    _, rt, _, rb = f.getbbox('Ag')
    w, h = r - l + 4, rb - rt + 4
    im = Image.new('L', (w, h), 0)
    ImageDraw.Draw(im).text((2 - l, 2 - rt), t, font=f, fill=255, stroke_width=1, stroke_fill=255)   # slightly heavier, like the print
    px = list(im.tobytes())
    if len(px) % 2: px.append(0)
    off = len(alpha)
    for i in range(0, len(px), 2):
        alpha.append((px[i] >> 4) | (px[i + 1] & 0xf0))
    # position of the bitmap's top-left corner in panel units
    pw, ph = w / RES, h / RES
    x0 = x - pw / 2 if anchor == 'c' else x
    y0 = y - ph / 2
    entries.append((x0, y0, pw, ph, w, h, col, off))

with open(OUT, 'w') as o:
    o.write('// Generated by tools/make_panel_art.py - do not edit.\n')
    o.write('// Front panel legends, typeset in GNU FreeSans (GPL with font exception), as 4-bit alpha.\n')
    o.write('#pragma once\n#include <cstdint>\n\n')
    o.write('struct PanelLegend { float x, y, w, h; uint16_t tw, th; uint8_t colour; uint32_t offset; };\n')
    o.write('static const PanelLegend PANEL_LEGENDS[] = {\n')
    for (x0, y0, pw, ph, w, h, col, off), item in zip(entries, L):
        o.write('    { %.1ff, %.1ff, %.2ff, %.2ff, %d, %d, %d, %d },   // %s\n' % (x0, y0, pw, ph, w, h, col, off,
                item[0].encode('ascii', 'backslashreplace').decode()))
    o.write('};\n\nstatic const uint8_t PANEL_LEGEND_ALPHA[] = {\n')
    for i in range(0, len(alpha), 24):
        o.write('    ' + ','.join('%d' % v for v in alpha[i:i + 24]) + ',\n')
    o.write('};\n')
print('%d legends, %d bytes -> %s' % (len(entries), len(alpha), OUT))
