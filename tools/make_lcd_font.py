    for code in range(65, 91):
        ch = chr(code)
        rows = d.get(ch) or fallback.get(ch) or ["."] * 6
        print("    {" + ",".join("0x%02x" % b for b in leg_bits(rows)) + "},  // " + ch)
    print("};\n")
